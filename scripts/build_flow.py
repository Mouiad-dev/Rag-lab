#!/usr/bin/env python3
"""Build the interactive pipeline/router view at docs/flow/index.html.

Inputs: config/pipeline_stages.json and config/techniques.json.
Usage:
    python scripts/build_flow.py          # validate and write the HTML
    python scripts/build_flow.py --check  # validate and fail if the HTML is stale
Standard library only; the output is one self-contained file (no CDN, works offline).
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STAGES = ROOT / "config" / "pipeline_stages.json"
CATALOG = ROOT / "config" / "techniques.json"
OUT = ROOT / "docs" / "flow" / "index.html"
ID_RE = re.compile(r"^[CR]\d{2}$")


def load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def validate(stages: dict, catalog: dict) -> list[str]:
    errors: list[str] = []
    ids = {t["id"] for t in catalog["techniques"]}
    stage_ids = {s["id"] for s in stages["stages"]}
    router_ids = {r["id"] for r in stages["routers"]}
    lanes = {ln["id"] for ln in stages["lanes"]}
    primary: dict[str, str] = {}
    for s in stages["stages"]:
        if s["lane"] not in lanes:
            errors.append(f"{s['id']}: unknown lane {s['lane']}")
        if s["router"] and s["router"] not in router_ids:
            errors.append(f"{s['id']}: unknown router {s['router']}")
        for tid in s["techniques"]:
            if tid not in ids:
                errors.append(f"{s['id']}: unknown technique {tid}")
            elif tid in primary:
                errors.append(f"{tid}: primary in both {primary[tid]} and {s['id']}")
            else:
                primary[tid] = s["id"]
        for tid in s["also"]:
            if tid not in ids:
                errors.append(f"{s['id']}: unknown 'also' technique {tid}")
    missing = sorted(ids - primary.keys())
    if missing:
        errors.append(f"techniques without a primary stage: {', '.join(missing)}")
    for group in ("documents", "questions"):
        for case in stages["demo"][group]:
            for sid, choice in case["route"].items():
                if sid not in stage_ids:
                    errors.append(f"demo {case['id']}: unknown stage {sid}")
                if ID_RE.match(choice["pick"]) and choice["pick"] not in ids:
                    errors.append(f"demo {case['id']}: unknown technique {choice['pick']}")
    return errors


def render(stages: dict, catalog: dict) -> str:
    keep = ("id", "name", "category", "family", "roadmap_step", "status", "mechanism", "acceptance", "primary_source")
    techniques = [{k: t.get(k) for k in keep} for t in catalog["techniques"]]
    data = {"stages": stages, "techniques": techniques}
    payload = json.dumps(data, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    return TEMPLATE.replace("__DATA__", payload)


def main() -> int:
    stages, catalog = load(STAGES), load(CATALOG)
    errors = validate(stages, catalog)
    if errors:
        print("FAIL:\n  " + "\n  ".join(errors))
        return 1
    html = render(stages, catalog)
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != html:
            print(f"FAIL: {OUT.relative_to(ROOT)} is stale; run python scripts/build_flow.py")
            return 1
        print(f"PASS: flow view up to date ({len(catalog['techniques'])} techniques mapped)")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(html, encoding="utf-8", newline="\n")
    print(
        f"Wrote {OUT.relative_to(ROOT)} ({len(catalog['techniques'])} techniques, "
        f"{len(stages['stages'])} stages, {len(stages['routers'])} routers)"
    )
    return 0


